// Ожидается ошибка компиляции E0382: использование после перемещения.
fn consume(s: String) -> usize {
    s.len()
} // здесь s выходит из области видимости, память строки освобождается

fn main() {
    let s = String::from("привет");
    let n = consume(s); // владение строкой перемещено в параметр consume
    println!("{n}");
    println!("{s}"); // ошибка: s больше ничем не владеет
}
